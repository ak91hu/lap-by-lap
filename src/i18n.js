export function normLang(l) {
  const v = String(l || '').trim().toLowerCase();
  return LANGS.includes(v) ? v : 'en';
}

export function t(lang, key, vars = {}) {
  const s = T[normLang(lang)][key] ?? T.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function sportName(lang, type) {
  if (!type) return lang === 'hu' ? 'Aktivitás' : 'Activity';
  const pair = SPORTS[type];
  if (pair) return pair[lang === 'hu' ? 0 : 1];
  return type.replace(/([a-z])([A-Z])/g, '$1 $2');
}
